package main

import (
	"bytes"
	"cmp"
	"fmt"
	"go/format"
	"go/token"
	"go/types"
	"maps"
	"os"
	"slices"
	"strings"
)

type options struct {
	patterns   []string
	importTags bool
}

// result is everything dstgen would write.
type result struct {
	outputs map[string][]byte   // path -> content; nil content means delete the file
	tags    map[string]*tagFile // directory -> its dst.tags
	errs    []string
}

// errorList collects errors with their positions.
type errorList struct{ list []posError }

type posError struct {
	pos token.Position
	msg string
}

func (e *errorList) add(pos token.Position, format string, args ...any) {
	e.list = append(e.list, posError{pos: pos, msg: fmt.Sprintf(format, args...)})
}

// sorted returns the errors by file, line and text, without duplicates.
func (e *errorList) sorted() []string {
	slices.SortFunc(e.list, func(a, b posError) int {
		return cmp.Or(cmp.Compare(a.pos.Filename, b.pos.Filename), cmp.Compare(a.pos.Line, b.pos.Line), cmp.Compare(a.msg, b.msg))
	})
	out := make([]string, 0, len(e.list))
	for _, p := range e.list {
		out = append(out, fmt.Sprintf("%s:%d: %s", p.pos.Filename, p.pos.Line, p.msg))
	}
	return slices.Compact(out)
}

// generate loads the packages and builds every output in memory.
func generate(opt options) (result, error) {
	units, err := load(opt.patterns)
	if err != nil {
		return result{}, err
	}
	res := result{outputs: map[string][]byte{}, tags: map[string]*tagFile{}}
	errs := &errorList{}
	byDir := map[string][]unit{}
	for _, u := range units {
		byDir[u.dir] = append(byDir[u.dir], u)
	}
	for _, dir := range slices.Sorted(maps.Keys(byDir)) {
		if err := generateDir(dir, byDir[dir], opt, &res, errs); err != nil {
			return result{}, err
		}
	}
	res.errs = errs.sorted()
	return res, nil
}

// generateDir handles the units of one directory, which share one dst.tags.
func generateDir(dir string, units []unit, opt options, res *result, errs *errorList) error {
	tags, err := readTags(dir + "/" + tagsFile)
	if err != nil {
		return err
	}
	scans := make([]scanned, len(units))
	var all []*annotated
	names := map[string]bool{}
	for i, u := range units {
		scans[i] = scan(u, errs)
		scans[i].validate(errs)
		all = append(all, scans[i].types...)
		for _, n := range u.pkg.Types.Scope().Names() {
			names[n] = true
		}
		if opt.importTags {
			tags.importTags(scans[i], errs)
		}
	}
	tags.retireMissing(func(name string) bool { return names[name] })
	tags.assign(all, errs)
	for i, u := range units {
		res.outputs[u.outPath()] = emitUnit(u, scans[i], tags, errs)
	}
	res.tags[dir] = tags
	res.outputs[tags.path] = tags.bytes()
	return nil
}

// emitUnit writes the generated file of one unit, or nil when it has nothing
// to generate.
func emitUnit(u unit, s scanned, tags *tagFile, errs *errorList) []byte {
	e := emitter{
		u: u, s: s, tags: tags, errs: errs,
		imports:   map[string]bool{},
		generated: map[*types.TypeName]bool{},
	}
	for _, a := range s.types {
		if a.message() && !a.manual && a.obj != nil {
			e.generated[a.obj] = true
		}
	}
	for _, a := range s.types {
		e.emitType(a)
	}
	if e.body.Len() == 0 {
		return nil
	}
	src := e.file()
	out, err := format.Source(src)
	if err != nil {
		errs.add(token.Position{Filename: u.outPath(), Line: 1}, "generated code does not parse (a dstgen bug): %v", err)
		return src
	}
	return out
}

type emitter struct {
	u         unit
	s         scanned
	tags      *tagFile
	errs      *errorList
	imports   map[string]bool
	generated map[*types.TypeName]bool
	body      strings.Builder
}

func (e *emitter) file() []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by dstgen. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", e.u.pkgName)
	if len(e.imports) > 0 {
		b.WriteString("import (\n")
		std, other := splitImports(e.imports)
		for _, p := range std {
			fmt.Fprintf(&b, "\t%q\n", p)
		}
		if len(std) > 0 && len(other) > 0 {
			b.WriteString("\n")
		}
		for _, p := range other {
			fmt.Fprintf(&b, "\t%q\n", p)
		}
		b.WriteString(")\n\n")
	}
	b.WriteString(e.body.String())
	return b.Bytes()
}

func (e *emitter) emitType(a *annotated) {
	if a.obj == nil {
		return
	}
	if a.message() {
		e.emitMessage(a)
	}
	if a.state {
		e.emitState(a)
	}
}

func (e *emitter) emitMessage(a *annotated) {
	tag, ok := e.tags.byName[a.name]
	if !ok {
		return // assign reported it
	}
	for _, sum := range a.cases {
		fmt.Fprintf(&e.body, "func (%s) %s() {}\n\n", a.name, markerName(sum))
	}
	fmt.Fprintf(&e.body, "// Tag returns the frozen trace-hash number of %s.\n", a.name)
	fmt.Fprintf(&e.body, "func (%s) Tag() uint64 { return %d }\n\n", a.name, tag)
	if a.manual {
		e.checkManual(a, tag)
	} else {
		e.emitFold(a, tag)
	}
	if a.answer != "" {
		e.emitAnswer(a)
	}
}

func (e *emitter) emitFold(a *annotated, tag uint64) {
	var body strings.Builder
	f := e.folder(a, &body)
	f.fold("x", a.obj.Type().Underlying(), true)
	e.imports[tracePath] = true
	fmt.Fprintf(&e.body, "// Fold writes %s into the trace hash: tag %d, then the fields in order.\n", a.name, tag)
	recv := "x " + a.name
	if body.Len() == 0 {
		recv = a.name
	}
	fmt.Fprintf(&e.body, "func (%s) Fold(h *trace.Hash) {\n\th.Uint64(%d)\n%s}\n\n", recv, tag, body.String())
}

func (e *emitter) folder(a *annotated, b *strings.Builder) *folder {
	return &folder{
		pkg: e.u.pkg.Types, generated: e.generated, imports: e.imports,
		b: b, pos: a.pos, errs: e.errs, what: a.name,
	}
}

func (e *emitter) checkManual(a *annotated, tag uint64) {
	for _, m := range e.s.methods[a.name] {
		if m.name == "Fold" && !manualFoldStartsWithTag(m.decl, tag) {
			e.errs.add(m.pos, "%s.Fold (//dst:fold manual) must start with h.Uint64(%d) or h.Uint64(x.Tag())", a.name, tag)
		}
	}
}

func (e *emitter) emitAnswer(a *annotated) {
	ans := e.s.byName[a.answer]
	obj, _ := e.u.pkg.Types.Scope().Lookup(a.answer).(*types.TypeName)
	switch {
	case obj == nil:
		e.errs.add(a.pos, "%s: //dst:answer %s: no such type in this package", a.name, a.answer)
		return
	case (ans == nil || !ans.message()) && !hasFold(obj.Type()):
		e.errs.add(a.pos, "%s: //dst:answer %s: the answer must be a payload (it has no Fold)", a.name, a.answer)
		return
	}
	fmt.Fprintf(&e.body, "// AsRequest ties %s to its answer %s for Perform.\n", a.name, a.answer)
	fmt.Fprintf(&e.body, "func (x %s) AsRequest() (%s, %s) {\n\tvar zero %s\n\treturn x, zero\n}\n\n",
		a.name, a.cases[0], a.answer, a.answer)
}

func (e *emitter) emitState(a *annotated) {
	st, ok := a.obj.Type().Underlying().(*types.Struct)
	if !ok {
		return // validate reported it
	}
	var body strings.Builder
	f := e.folder(a, &body)
	f.what = a.name + " (state)"
	for i := range st.NumFields() {
		fl := st.Field(i)
		if fl.Name() == "_" || skipped(st.Tag(i)) {
			continue
		}
		f.fold("x."+fl.Name(), fl.Type(), true)
	}
	e.imports[tracePath] = true
	fmt.Fprintf(&e.body, "// StateHash folds every field of %s except those tagged dst:\"skip\".\n", a.name)
	fmt.Fprintf(&e.body, "func (x *%s) StateHash() uint64 {\n\tsum := trace.New()\n\th := &sum\n%s\treturn sum.Sum()\n}\n\n",
		a.name, body.String())
}

// skipped reports a struct tag dst:"skip".
func skipped(tag string) bool {
	return slices.Contains(strings.Fields(tag), `dst:"skip"`)
}

// staleFiles lists the outputs that differ from the files on disk.
func staleFiles(res result) []string {
	var stale []string
	for _, path := range slices.Sorted(maps.Keys(res.outputs)) {
		want := res.outputs[path]
		have, err := os.ReadFile(path) //nolint:gosec // an output path dstgen built itself
		if os.IsNotExist(err) {
			have, err = nil, nil
		}
		if err != nil || !bytes.Equal(have, want) {
			stale = append(stale, path)
		}
	}
	return stale
}

// writeOutputs writes every output; a nil output removes the file.
func writeOutputs(res result) error {
	for _, path := range slices.Sorted(maps.Keys(res.outputs)) {
		data := res.outputs[path]
		if data == nil {
			if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
				return err
			}
			continue
		}
		if err := os.WriteFile(path, data, 0o644); err != nil { //nolint:gosec // generated source is world-readable like any source file
			return err
		}
	}
	return nil
}

// splitImports returns the standard library imports and the others, each
// sorted. A standard library path has no dot in its first element.
func splitImports(imports map[string]bool) ([]string, []string) {
	var std, other []string
	for _, p := range slices.Sorted(maps.Keys(imports)) {
		first, _, _ := strings.Cut(p, "/")
		if strings.Contains(first, ".") {
			other = append(other, p)
		} else {
			std = append(std, p)
		}
	}
	return std, other
}
